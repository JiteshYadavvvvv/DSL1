//"In brightest day, in blackest night, no question shall escape my sight. 
//Let those who worship difficulty's might, beware my power
//crazy man's light!"
ll dp[100000+1][101];
void solve(int ttc){
   ll n;
   cin>>n;
   ll m;
   cin>>m;
   vi v(n);
   in(v);
   
   for(int i=0;i<n;i++){
	if(v[i]!=0){
		for(int k=max(v[i]-1,1LL);k<=min(v[i]+1+0LL,m);k++){
			dp[i][v[i]]=(dp[i][v[i]]+dp[i-1][k])%mo;
		}
		continue;
	}
	for(int j=1;j<=m;j++){
		for(int k=max(j-1,1);k<=min(j+1+0LL,m);k++){
			dp[i][k]=(dp[i][k]+dp[i-1][k])%mo;
		}
	}
   }
   ll ans=0;
   for(int i=1;i<=m;i++){
	ans=(ans+dp[n][i])%mo;
   }
   cout<<ans;
}
signed main(){
   int t;
   t=1;
   //cin>>t;
   for(int i=1;i<=t;i++){
      solve(i);
      cout<<"\n";
   }
}

